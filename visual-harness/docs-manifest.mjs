// visual-harness/docs-manifest.mjs — SC-142 phase 2a: the single source of truth for
// EVERY screenshot in README.md and docs/**.
//
// One entry per image file in docs/Media. `npm run docs-shots` walks this list and
// regenerates each one from the real plugin — the browser harness for pure element cards,
// real Obsidian (on a virtual display) for the surfaces only the app has: the settings
// pages, modals, canvas, the sidebar.
//
// WHY A MANIFEST rather than ad-hoc captures: before this, every docs image was a manual
// screenshot whose provenance lived in nobody's head — by 7.0.0 every one of them except
// roll.png predated the Steel rendering work and showed a plugin that no longer existed
// (SC-142 phase 1 report). An image that cannot be regenerated by a command is an image
// that will be stale again by the next release.
//
// ADDING AN IMAGE: add an entry here, reference `docs/Media/<out>` from the doc, run
// `npm run docs-shots`. Nothing else knows about docs images — no list to keep in sync.
//
// This file is deliberately separate from `visual-harness/entry.ts`'s FIXTURES and from
// `shoot.mjs`'s sweep: docs images are a PUBLISHING surface with its own framing rules,
// and the `shots`/freeze/parity gates must not move when a docs image does. Nothing here
// writes to visual-harness/shots/.
//
// ---------------------------------------------------------------------------------------
// ENTRY SHAPES
//
//   source: 'browser'  — rendered through the F4 harness page (visual-harness/index.html),
//                        which mounts the real ElementPipeline in Chromium. Fast, needs no
//                        display, deterministic.
//     { out, source: 'browser', element, fixture?, bg?, width?, prefs?, gallery? }
//
//   source: 'obsidian' — captured from a real Obsidian instance driven over CDP
//                        (obsidian-camera.mjs --docs). Needed for anything that is not an
//                        element card: settings, modals, canvas, sidebar.
//     kind: 'note'     { out, note? | body?, element, mode? }        a rendered note
//     kind: 'settings' { out, page? }                                the settings tab
//     kind: 'modal'    { out, note? | body?, trigger, ready, then?, pref?, clip? }
//     kind: 'sidebar'  { out, note? | body?, element? }              a real sidebar leaf
//     kind: 'canvas'   { out, canvas }                               a real canvas
//
//   `body` writes a docs-only note into the (git-ignored, regenerated) demo-vault Harness
//   folder, so a docs image can show content no element fixture has — without adding a
//   fixture, which would move the `npm run shots` count and the frozen baselines.
// ---------------------------------------------------------------------------------------

